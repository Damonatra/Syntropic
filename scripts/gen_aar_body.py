def on_page(canvas, doc):
    canvas.saveState()
    # Header: title left + accent rule
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 44, DOC_TITLE)
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 52, PAGE_W - MARGIN, PAGE_H - 52)
    # Footer: light rule + author left + page number right
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 46, PAGE_W - MARGIN, 46)
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 34, 'Backbone Engineering Cell')
    if doc.page <= TOC_PAGES:
        num = ROMAN.get(doc.page, str(doc.page))
    else:
        num = str(doc.page - TOC_PAGES)
    canvas.drawRightString(PAGE_W - MARGIN, 34, num)
    canvas.restoreState()


