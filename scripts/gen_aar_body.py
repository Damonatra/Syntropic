# ━━ Doc template with TOC support ━━
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            # All headings live in the body (after the single TOC front-matter
            # page); report the DISPLAYED folio (physical body page - 1) so the
            # TOC matches the footer numbering scheme (front matter = i,
            # body resets to arabic 1).
            self.notify('TOCEntry', (level, text, self.page - 1, key))


def add_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def H1(story, text):
    """Major section heading: orphan guard + heading + accent rule."""
    story.append(CondPageBreak(H1_ORPHAN))
    head = add_heading(text, h1, level=0)
    rule = HRFlowable(width='100%', thickness=1.2, color=ACCENT,
                      spaceBefore=5, spaceAfter=12)
    story.extend(safe_keep_together([head, rule]))


def H2(story, text, first_para=None):
    head = add_heading(text, h2, level=1)
    if first_para is not None:
        story.extend(safe_keep_together([head, first_para]))
    else:
        story.append(head)


def embed_image(path, max_width=AVAIL_W, max_height=PAGE_H * 0.35):
    pil = PILImage.open(path)
    ow, oh = pil.size
    ratio = min(max_width / ow if ow > max_width else 1.0,
                max_height / oh if oh > max_height else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def make_table(header, rows, ratios, style_extra=None, align_center_cols=()):
    assert abs(sum(ratios) - 1.0) < 0.01, 'ratios must sum to 1'
    col_widths = [r * AVAIL_W for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5
    data = [[Paragraph('<b>%s</b>' % c, th) for c in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = td_c if i in align_center_cols else td
            cells.append(Paragraph(c, st))
        data.append(cells)
    t = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    base = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5.5),
    ]
    for i in range(1, len(data)):
        base.append(('BACKGROUND', (0, i), (-1, i),
                     TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    if style_extra:
        base.extend(style_extra)
    t.setStyle(TableStyle(base))
    return t


def add_table(story, header, rows, ratios, cap, align_center_cols=(), style_extra=None):
    t = make_table(header, rows, ratios, style_extra, align_center_cols)
    story.append(Spacer(1, 14))
    story.append(t)
    story.append(Spacer(1, 6))
    story.append(Paragraph(cap, caption))
    story.append(Spacer(1, 14))


def stat_row(story, stats):
    """Single full-width segmented stat strip (4 columns, shared accent frame)."""
    box_w = AVAIL_W / 4
    top = [Paragraph('<b>%s</b>' % val, stat_big) for val, _ in stats]
    bottom = [Paragraph(lab, stat_label) for _, lab in stats]
    strip = Table([top, bottom], colWidths=[box_w] * 4, hAlign='CENTER')
    style = [
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('BOX', (0, 0), (-1, -1), 0.9, ACCENT),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, 0), 9),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ('TOPPADDING', (0, 1), (-1, 1), 1),
        ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
    ]
    for c in range(1, 4):
        style.append(('LINEBEFORE', (c, 0), (c, -1), 0.9, ACCENT))
    strip.setStyle(TableStyle(style))
    story.append(Spacer(1, 8))
    story.append(strip)
    story.append(Spacer(1, 12))


